# Public fixtures. Each encryption case has a unique nonce; decryptions replay
# that same message, including deliberate authentication-failure variants.
cases=[]
for i,n in enumerate([0,1,15,16,17,32,64]):
 key=bytes(range(16));nonce=(0x53540000+i).to_bytes(16,'little');ad=bytes(range([0,1,15,16,17,32,3][i]));pt=bytes((j*13+i)%256 for j in range(n));ct,tag=encrypt(key,nonce,ad,pt)
 cases.extend([(False,False,key,nonce,ad,pt,ct,tag),(True,False,key,nonce,ad,ct,pt,tag)])
 # Tampering checks tag, nonce, AD and ciphertext across full and partial cases.
 if i in [2,3,4,6]:
  typ={2:'tag',3:'nonce',4:'ad',6:'ct'}[i]
  flip=lambda b:bytes([b[0]^1])+b[1:]
  nn=flip(nonce) if typ=='nonce' else nonce;aa=flip(ad) if typ=='ad' else ad;cc=flip(ct) if typ=='ct' else ct;tt=flip(tag) if typ=='tag' else tag
  # Provisional plaintext can differ on tampered input; use reference encryption
  # keystream only for good messages and skip byte equality on failed cases.
  cases.append((True,True,key,nn,aa,cc,pt,tt))
def hx(b):return 'x"'+b.ljust(16,b'\0')[::-1].hex().upper()+'"'
def blocks(b):
 c=[b[i:i+16] for i in range(0,len(b),16)] or [b''];return '('+', '.join(f'{i} => {hx(x)}' for i,x in enumerate(c))+', others => (others => \'0\'))' if len(c)<4 else '('+', '.join(hx(x) for x in c)+')'
